const { test } = require('node:test');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const { webcrypto } = require('node:crypto');
const code = fs.readFileSync(require('node:path').join(__dirname, '../preview-cache.js'), 'utf8');
function browser(entries = new Map(), fetcher) {
  const cache = {
    async match(key) { return entries.get(typeof key === 'string' ? key : key.url)?.clone(); },
    async put(key, response) { entries.set(typeof key === 'string' ? key : key.url, response.clone()); },
    async keys() { return [...entries.keys()].map(url => new Request(url)); },
    async delete(key) { return entries.delete(typeof key === 'string' ? key : key.url); }
  };
  const w = { crypto: webcrypto, location: { href: 'https://studio.test/library/' }, caches: { open: async () => cache }, fetch: fetcher };
  vm.runInNewContext(code, { window: w, TextEncoder, URL, Blob, Response });
  return { api: w.StudioPreviewCache, entries };
}
const options = { limit: 1048576, kind: 'video' };
// Exercise the application's actual clip/cache policy with the real preview-byte cache.
function appClip(cache, resolver) {
  const app = fs.readFileSync(require('node:path').join(__dirname, '../app.js'), 'utf8');
  const scope = { window: { StudioPreviewCache: cache, OpenListClient: { resolveClipCached: resolver } } };
  vm.runInNewContext(app.slice(app.indexOf('  function previewKey('), app.indexOf('  function clearThumbnails(')) + '\nthis.policy = { previewKey, loadClip };', scope);
  return scope.policy;
}
test('the app clip loader ignores old originals and reuses only generated bytes below 8 MiB', async () => {
  const input = { provider: 'openlist', folderUrl: 'https://library.test/', folderPath: '/' }, session = { username: 'member' };
  const asset = { id: 'gif', provider: 'openlist', managed: true, modified: 'today', sizeMB: 1024, revision: 1 };
  const entries = new Map(); let downloads = 0, resolutions = 0;
  const b = browser(entries, async url => { downloads++; return new Response(url.includes('old') ? 'original bytes' : 'generated bytes', { headers: { 'Content-Type': url.includes('old-gif') ? 'image/gif' : 'video/mp4' } }); });
  const app = appClip(b.api, async () => { resolutions++; return 'https://cdn.test/generated.mp4'; });
  await b.api.load(app.previewKey(input, session, asset, 'video'), () => 'https://cdn.test/old-video', { kind: 'video', limit: 2048 });
  await b.api.load(app.previewKey(input, session, asset, 'image'), () => 'https://cdn.test/old-gif', { kind: 'image', limit: 2048 });
  const first = await app.loadClip(input, session, asset);
  assert.equal(await first.blob.text(), 'generated bytes'); assert.equal(first.cached, false);
  assert.equal(downloads, 3); assert.equal(resolutions, 1);
  const second = await app.loadClip(input, session, asset);
  assert.equal(second.cached, true); assert.equal(downloads, 3); assert.equal(resolutions, 1);
  await app.loadClip(input, session, { ...asset, revision: 2 }); assert.equal(resolutions, 2);
  await assert.rejects(app.loadClip(input, session, { ...asset, provider: 'google' })); assert.equal(resolutions, 2);
  const oversized = browser(new Map(), async () => new Response(new Uint8Array(8 * 1048576 + 1), { headers: { 'Content-Type': 'video/mp4' } }));
  await assert.rejects(appClip(oversized.api, async () => 'https://cdn.test/large').loadClip(input, session, asset), /超过/);
  assert.equal(oversized.entries.size, 0);
});
test('checking for a local original does not download; cached parts survive a new page with account and version isolation', async () => {
  let requests = 0;
  const entries = new Map();
  const b = browser(entries, async () => { requests++; return new Response('local original', { headers: { 'Content-Type': 'image/png' } }); });
  const parts = ['member', 'image', 'revision-1'];
  const opts = { kind: 'image', limit: 1024 };
  assert.equal(await b.api.peek(parts, opts), null);
  assert.equal(requests, 0);
  await b.api.load(parts, () => 'https://cdn.test/original', opts);
  const next = browser(entries, async () => { throw Error('must not request'); });
  assert.equal(await (await next.api.peek(parts, opts)).blob.text(), 'local original');
  assert.equal(await next.api.peek(['other-member', 'image', 'revision-1'], opts), null);
  assert.equal(await next.api.peek(['member', 'image', 'revision-2'], opts), null);
  const controller = new AbortController(); controller.abort();
  await assert.rejects(next.api.peek(parts, { ...opts, signal: controller.signal }));
  assert.equal(requests, 1);
});
test('expired preview links renew once; cached bytes need neither the stale URL nor another backend request', async () => {
  let downloads = 0, renewals = 0;
  const b = browser(new Map(), async url => {
    downloads++;
    return url.endsWith('/expired') ? new Response('expired', { status: 403 }) : new Response('image bytes', { headers: { 'Content-Type': 'image/png' } });
  });
  const opts = { limit: 1024, kind: 'image', refreshUrl: async () => { renewals++; return 'https://cdn.test/fresh'; } };
  const first = await b.api.load(['renewable'], () => 'https://cdn.test/expired', opts);
  assert.equal(first.cached, false); assert.equal(downloads, 2); assert.equal(renewals, 1);
  const next = await b.api.load(['renewable'], () => { throw Error('cache must skip URL resolution'); }, opts);
  assert.equal(next.cached, true); assert.equal(downloads, 2); assert.equal(renewals, 1);
});
test('failed renewals stop after one attempt and do not poison a later refresh', async () => {
  let available = false, downloads = 0, renewals = 0;
  const b = browser(new Map(), async () => {
    downloads++;
    return available ? new Response('image', { headers: { 'Content-Type': 'image/png' } }) : new Response('unavailable', { status: 503 });
  });
  const opts = { limit: 1024, kind: 'image', refreshUrl: () => { renewals++; return 'https://cdn.test/fresh'; } };
  await assert.rejects(b.api.load(['retryable'], () => 'https://cdn.test/expired', opts));
  assert.equal(downloads, 2); assert.equal(renewals, 1); assert.equal(b.entries.size, 0);
  available = true;
  assert.equal((await b.api.load(['retryable'], () => 'https://cdn.test/fresh', opts)).cached, false);
  assert.equal(downloads, 3); assert.equal(renewals, 1);
});
test('cancelling a thumbnail never starts link renewal', async () => {
  const controller = new AbortController();
  const b = browser(new Map(), async () => { controller.abort(); throw Error('network interrupted'); });
  await assert.rejects(b.api.load(['cancelled-thumb'], () => 'https://cdn.test/thumb', { signal: controller.signal, kind: 'image', limit: 1024, refreshUrl: () => { throw Error('must not renew'); } }));
  assert.equal(b.entries.size, 0);
});
test('binary cloud thumbnails are identified by PNG, JPEG, GIF and WebP signatures and cached as images', async () => {
  for (const [signature, type] of [
    [[0x89,0x50,0x4e,0x47,0x0d,0x0a,0x1a,0x0a], 'image/png'],
    [[0xff,0xd8,0xff,0xe0], 'image/jpeg'],
    [[0x47,0x49,0x46,0x38,0x39,0x61], 'image/gif'],
    [[0x52,0x49,0x46,0x46,0,0,0,0,0x57,0x45,0x42,0x50], 'image/webp']
  ]) {
    const b = browser(new Map(), async () => new Response(new Uint8Array(signature), { headers: { 'Content-Type':'application/octet-stream' } }));
    const loaded = await b.api.load([type], () => 'https://cdn.test/thumb', { kind:'image', limit:4*1048576 });
    assert.equal(loaded.blob.type, type);
    assert.equal(b.entries.size, 1);
    const cached = await b.api.load([type], () => { throw Error('must use cache'); }, { kind:'image', limit:4*1048576 });
    assert.equal(cached.cached, true);
  }
});
test('binary HTML and unknown data never become cached thumbnails; larger valid thumbnails respect the new limit', async () => {
  for (const data of ['<html>not a picture</html>', 'random binary data']) {
    const b = browser(new Map(), async () => new Response(data, { headers:{'Content-Type':'application/octet-stream'} }));
    await assert.rejects(b.api.load(['not-image'], () => 'https://cdn.test/thumb', {kind:'image',limit:4*1048576}));
    assert.equal(b.entries.size, 0);
  }
  const bytes = new Uint8Array(1105991); bytes.set([0xff,0xd8,0xff]);
  const b = browser(new Map(), async () => new Response(bytes, {headers:{'Content-Type':'image/jpeg','Content-Length':String(bytes.length)}}));
  const loaded = await b.api.load(['large-thumb'], () => 'https://cdn.test/thumb', {kind:'image',limit:4*1048576});
  assert.equal(loaded.blob.size, 1105991);
  const tooLarge = browser(new Map(), async () => new Response(bytes,{headers:{'Content-Type':'image/jpeg','Content-Length':String(4*1048576+1)}}));
  await assert.rejects(tooLarge.api.load(['too-large'], () => 'https://cdn.test/thumb', {kind:'image',limit:4*1048576}));
  assert.equal(tooLarge.entries.size, 0);
});
test('persistent preview survives a new page without a resolver or network request; version and account isolate entries', async () => {
  const entries = new Map(); let calls = 0, resolutions = 0;
  const first = browser(entries, async () => { calls++; return new Response('low-quality-bytes', { headers: { 'Content-Type': 'video/mp4' } }); });
  const parts = ['backend', 'member01', 'movie', 'modified-1'];
  const result = await first.api.load(parts, async () => { resolutions++; return 'https://cdn.test/private-link?sign=temporary'; }, options);
  assert.equal(result.persistent, true);
  const nextPage = browser(entries, async () => { throw Error('must not fetch'); });
  const cached = await nextPage.api.load(parts, () => { throw Error('must not resolve'); }, options);
  assert.equal(cached.cached, true);
  assert.equal(await cached.blob.text(), 'low-quality-bytes');
  assert.equal(calls, 1); assert.equal(resolutions, 1);
  assert.notEqual(await first.api.key(parts), await first.api.key(['backend', 'member02', 'movie', 'modified-1']));
  assert.notEqual(await first.api.key(parts), await first.api.key(['backend', 'member01', 'movie', 'modified-2']));
  assert.equal([...entries.keys()].some(key => key.includes('sign=') || key.includes('member01')), false);
});
test('oversize original, HTML, partial response and incomplete downloads never enter the preview cache', async () => {
  for (const headers of [{ 'Content-Type': 'video/quicktime', 'Content-Length': '404869412' }, { 'Content-Type': 'text/html' }]) {
    const b = browser(new Map(), async () => new Response('bytes', { headers }));
    await assert.rejects(b.api.load(['reject'], () => 'https://cdn.test/source', options));
    assert.equal(b.entries.size, 0);
  }
  const b = browser(new Map(), async () => new Response(new Uint8Array(1025), { headers: { 'Content-Type': 'video/mp4' } }));
  await assert.rejects(b.api.load(['unbounded'], () => 'https://cdn.test/source', { ...options, limit: 1024 }));
  assert.equal(b.entries.size, 0);
  const partial = browser(new Map(), async () => new Response('fragment', { status: 206, headers: { 'Content-Type': 'video/mp4' } }));
  await assert.rejects(partial.api.load(['partial'], () => 'https://cdn.test/video', options));
  assert.equal(partial.entries.size, 0);
  const incomplete = browser(new Map(), async () => new Response('short', { headers: { 'Content-Type': 'video/mp4', 'Content-Length': '100' } }));
  await assert.rejects(incomplete.api.load(['incomplete'], () => 'https://cdn.test/video', options));
  assert.equal(incomplete.entries.size, 0);
});
test('closed preview aborts before resolution; unavailable browser storage still reuses this page memory', async () => {
  const aborted = new AbortController(); aborted.abort();
  const b = browser(new Map(), async () => { throw Error('unexpected fetch'); });
  await assert.rejects(b.api.load(['closed'], () => { throw Error('unexpected resolver'); }, { ...options, signal: aborted.signal }));
  const w = { crypto: webcrypto, location: { href: 'https://studio.test/' }, fetch: async () => new Response('image', { headers: { 'Content-Type': 'image/jpeg' } }) };
  vm.runInNewContext(code, { window: w, TextEncoder, URL, Blob, Response });
  const result = await w.StudioPreviewCache.load(['no-disk'], () => 'https://cdn.test/thumb', { limit: 1024, kind: 'image' });
  assert.equal(result.persistent, false);
  const next = await w.StudioPreviewCache.load(['no-disk'], () => { throw Error('must not resolve'); }, { limit: 1024, kind: 'image' });
  assert.equal(next.cached, true);
});
